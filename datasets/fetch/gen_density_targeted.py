"""Density-controlled synthetic streams from this project's own generator
(synth_corr_gen.make_density_targeted_dataset): the fraction of (pair, lag, window) tuples above the
threshold is set to --density and VERIFIED by brute force (within --tolerance), for a stationary or a
nonstationary base process, at the protocol (W, step, L, T) the cell will run. Density is therefore a
property of the file at that protocol, which is why one file is generated per (process, density, T).
By default the group size (degree + 1) is solved from the density; `--degree` fixes it and the density
then only chooses the number of groups (refused when unreachable). The effective degree, measured on
the verified ground truth, is recorded in meta. Also writes the experiment config next to the file.

    python datasets/fetch/gen_density_targeted.py --proc ar1 --density 0.02 --T 0.9 --m 1000 --n 20000 --W 168 --step 12 --L 1
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from _common import OUT_DIR, REPO, save_competitor_npz

PROCS = {
    "ar1": {"type": "ar1", "phi": 0.6, "sigma": 1.0},                       # stationary
    "wn": {"type": "wn", "sigma": 1.0},                                       # stationary, white (uncooperative)
    "ou": {"type": "ou", "theta": 0.4, "mu": 0.0, "dt": 1.0, "sigma": 1.0},   # stationary
    "rw": {"type": "rw", "sigma": 1.0, "obs_sigma": 0.0},                    # nonstationary (cooperative)
    "rw_seasonal_drift": {"type": "rw_seasonal_drift", "drift": 0.04, "season_amplitude": 0.6, "season_period": 288, "sigma": 0.8, "obs_sigma": 0.0},
}

CONFIG = '''"""Dataset-level configuration: {name} (generated by datasets/fetch/gen_density_targeted.py).
Base process {proc} ({stat}), verified tuple density {density} at T={T}, W={W}, step={step}, L={L}; m={m}, n={n}.
Density holds at THIS protocol only: run the cell with exactly these W/step/n_lags/T.
"""

from functools import partial

from datasets.competitor_loader import load_dataset

RESULT_FOLDER = "competitor_exp/{name}"
DATASET = ["{name}"]
N_SERIES = [{m}]
N_OBS = [{n}]
OBS_MODE = "count"

DATA_LOADER = partial(load_dataset, name="{name}")
'''


def main() -> None:
    import sys
    sys.path.insert(0, str(REPO))
    from synth_corr_gen import make_density_targeted_dataset, _stationarity_tag

    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--proc", choices=sorted(PROCS), required=True)
    ap.add_argument("--density", type=float, required=True, help="target tuple density, e.g. 0.005, 0.02, 0.05")
    ap.add_argument("--T", type=float, required=True)
    ap.add_argument("--m", type=int, default=1000)
    ap.add_argument("--n", type=int, default=20000)
    ap.add_argument("--W", type=int, default=168)
    ap.add_argument("--step", type=int, default=12)
    ap.add_argument("--L", type=int, default=1, help="lagged windows; n_lags = (L - 1) * step")
    ap.add_argument("--corr-sign", default="both")
    ap.add_argument("--degree", type=int, default=None, help="fix the degree: group_size = degree + 1, the density then only picks the number of groups "
                                                             "(refused when unreachable); the effective degree measured on the verified truth is recorded")
    ap.add_argument("--preprocess", action="store_true", help="define the density in the differenced space")
    ap.add_argument("--tolerance", type=float, default=0.15)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--name", default=None)
    args = ap.parse_args()
    n_lags = (args.L - 1) * args.step
    name = args.name or f"synth_{args.proc}_d{str(args.density).replace('.', 'p')}_T{str(args.T).replace('.', 'p')}_m{args.m}_L{args.L}{'_deg' + str(args.degree) if args.degree is not None else ''}{'_diff' if args.preprocess else ''}"
    out = make_density_targeted_dataset(m=args.m, n=args.n, target_density=args.density, corr_threshold=args.T, window_size=args.W,
                                        window_step=args.step, n_lags=n_lags, n_eval_steps=max(50, (args.n - args.W) // args.step // 4),
                                        base_proc=PROCS[args.proc], preprocess=args.preprocess, corr_sign=args.corr_sign, seed=args.seed,
                                        tolerance=args.tolerance, verify_bf=True, group_size=(args.degree + 1) if args.degree is not None else None)
    data = np.asarray(out["data"], dtype=np.float64)[:, 1:].T          # (m, n)
    meta = {"source": "synth_corr_gen.make_density_targeted_dataset", "base_proc": PROCS[args.proc], "stationarity": _stationarity_tag(PROCS[args.proc]),
            "target_density": args.density, "analytic_density": out["analytic_density"], "verified_density": out["verified_density"],
            "group_size": out["group_size"], "n_groups": out["n_groups"], "degree_by_construction": int(out["group_size"]) - 1,
            "effective_degree": out.get("effective_degree"), "requested_degree": args.degree,
            "protocol": {"W": args.W, "step": args.step, "n_lags": n_lags, "L": args.L, "T": args.T, "preprocess": args.preprocess, "corr_sign": args.corr_sign},
            "seed": args.seed, "regime": f"synthetic, {_stationarity_tag(PROCS[args.proc])}, density-controlled"}
    path = save_competitor_npz(name, data, list(out["ids"]), meta)
    with np.load(path, allow_pickle=True) as z:
        arrays = {k: z[k] for k in z.files}
    arrays["gt_rows"] = np.asarray(out["gt_rows"], dtype=np.int64); arrays["gt_corrs"] = np.asarray(out["gt_corrs"], dtype=np.float64)
    np.savez_compressed(path, **arrays)
    cfg_dir = OUT_DIR / "configs"; cfg_dir.mkdir(parents=True, exist_ok=True)
    cfg = cfg_dir / f"experiment_dataset_{name}.py"
    cfg.write_text(CONFIG.format(name=name, proc=args.proc, stat=meta["stationarity"], density=out["verified_density"], T=args.T, W=args.W, step=args.step, L=args.L, m=args.m, n=args.n))
    print(f"config {cfg}; {out['n_groups']} groups of {out['group_size']} (degree {meta['degree_by_construction']}, effective {out.get('effective_degree', 0):.2f}); verified density {out['verified_density']:.4f}")


if __name__ == "__main__":
    main()
